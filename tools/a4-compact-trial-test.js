const fs = require('fs');
const vm = require('vm');
const path = require('path');
const assert = require('assert');
const app = fs.readFileSync(path.join(__dirname, '..', 'app-upload.js'), 'utf8');
const state = { methodology: {locale:''}, a3: {finalGap:'Original gap retained'}, a4: {literatureProblem:'My saved problem <text>',refinedGap:'Saved wording',gapRevisionReason:'My explanation',questions:[],questionPurposes:[],questionClaims:[],questionFocuses:[]} };
const before = JSON.stringify(state);
const ctx = vm.createContext({state,els:{stageForm:{innerHTML:''}},rqPurposeOptions:{},SRQ_LIMITS:{minimum:2,maximum:7},escapeHtml:value=>String(value || '').replace(/</g,'&lt;').replace(/>/g,'&gt;'),contextTaskLink:()=>'<button data-context-stage="a3">A3: Final Gap</button>',exampleControl:()=>'<button data-example-stage="a4">View example</button>'});
vm.runInContext(app.slice(app.indexOf('function renderA4()'), app.indexOf('function questionStarterHint')),ctx);
vm.runInContext('renderA4()',ctx);
const html = ctx.els.stageForm.innerHTML;
assert(html.includes('My saved problem &lt;text&gt;'));
assert(html.includes('Saved wording'));
assert(html.includes('My explanation'));
assert(html.includes('Original gap retained'));
assert(html.includes('Saved refinement'));
assert(html.includes('data-gap-revision-reason >'));
assert(html.indexOf('id="a4-literature-problem"') < html.indexOf('<details class="gap-refinement'));
assert(html.includes('<details class="a4-prompt-guidance">'));
assert(html.includes('What problem becomes visible from your literature gap?'));
assert(html.includes('data-context-stage="a3"'));
assert(html.includes('data-example-stage="a4"'));
assert(html.includes('Central Study Focus: What phenomenon, relationship, process, alignment, or condition will be investigated?'));
assert.strictEqual(JSON.stringify(state),before);
console.log('Passed: saved answers/refinement/reason preserved, response-first ordering, collapsed guidance, source/example access, and unchanged A4.2 prompt.');
