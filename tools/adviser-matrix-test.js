const fs = require('fs');
const path = require('path');
const vm = require('vm');
const assert = require('assert');
const root = path.resolve(__dirname, '..');
const nodes = {};
const masters = { proposals: {}, parts: {} };
nodes.adviserMatrixChoices = { querySelector: selector => masters[selector.includes('proposals') ? 'proposals' : 'parts'] };
const context = vm.createContext({ URL, document: { getElementById: id => nodes[id] ||= {} }, window: { location: { href: 'https://example.test/index.html?role=adviser' } } });
vm.runInContext(fs.readFileSync(path.join(root, 'adviser-workspace.js'), 'utf8'), context);
const store = context.ADVISER_STORE;
const parts = store.parts;
assert.strictEqual(new Set(parts.map(part => part.id)).size, parts.length);
const long = 'A detailed full response.\n'.repeat(500) + '<script>not HTML</script>';
const source = { a1: { coreConstruct: long }, a4: { questions: ['First question?', '', 'Third question?'], questionClaims: ['First claim', '', 'Third claim'] }, instrumentation: { rows: [{rq:'First question?',evidenceNeeded:'Records', instrument:'Rubric', analysis:'Scores',validation:'Review'}] }, terms: { rows: [{term:'Term',operational:'Meaning',conceptual:'Source',measured:'Test'}] }, submission: { groupName: 'Group <one>' } };
const before = JSON.stringify(source);
for (const part of parts) {
  assert.strictEqual(typeof store.entry(source, part), 'string');
  const target = new URL(store.sourceUrl('https://example.test/index.html?sourcePart=gap', {id:'copy one'}, part));
  assert.strictEqual(target.searchParams.get('proposal'), 'copy one');
  assert.strictEqual(target.searchParams.get('sourcePart'), part.id);
  assert(store.sourceSelector(part, source).startsWith('['));
}
assert.strictEqual(store.entry(source, parts[0]), long);
assert.strictEqual(store.entry(source, parts.find(p => p.id === 'questions')), '1. First question?\n\n3. Third question?');
assert(store.entry(source, parts.find(p => p.id === 'instruments')).includes('Quality checks: Review'));
assert(store.entry(source, parts.find(p => p.id === 'terms')).includes('Meaning\nSource\nTest'));
assert.strictEqual(JSON.stringify(source), before, 'Matrix extraction mutated original entries');
assert(!store.url('https://example.test/?role=adviser&proposal=x&sourcePart=gap', 'researcher').includes('sourcePart'));
const app = fs.readFileSync(path.join(root, 'app-upload.js'), 'utf8');
context.escapeHtml = s => String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');
context.formatTimestamp = s => s;
vm.runInContext(app.slice(app.indexOf('let adviserMatrixSelection = null;'), app.indexOf('function adviserNavigationButton')), context);
const records = [{id:'one',fileName:'one.json',importedAt:'today',payload:source},{id:'two',fileName:'two.json',importedAt:'today',payload:{a1:{},submission:{groupName:'Group 2'}}}];
context.records = records;
vm.runInContext('renderAdviserMatrixChoices(records)', context);
assert(masters.proposals.checked);
assert(!masters.proposals.indeterminate);
assert(!masters.parts.checked);
assert(masters.parts.indeterminate);
let html = nodes.adviserMatrixResult.innerHTML;
assert(html.includes('--proposal-count: 2'), 'Column count must follow selected proposals');
assert(html.includes(context.escapeHtml(long)), 'Full response was truncated');
assert(!html.includes('<script>'));
assert(html.includes('Group &lt;one&gt;'));
assert(html.includes('Not yet entered'));
assert.strictEqual((html.match(/<td>/g)||[]).length, 6);
assert(html.includes('aria-label="View source task: Core construct'));
assert(html.includes('<svg'));
vm.runInContext('adviserMatrixSelection.proposals.delete("two"); adviserMatrixSelection.parts = new Set(["questions"]); renderAdviserMatrix(records)', context);
assert.strictEqual((nodes.adviserMatrixResult.innerHTML.match(/<td>/g)||[]).length, 1);
assert(nodes.adviserMatrixResult.innerHTML.includes('adviser-matrix-single'));
assert(nodes.adviserMatrixResult.innerHTML.includes('--proposal-count: 1'));
vm.runInContext('adviserMatrixSelection.parts.clear(); renderAdviserMatrix(records)', context);
assert(nodes.adviserMatrixResult.innerHTML.includes('Select at least one'));
assert.strictEqual(JSON.stringify(source), before);
assert.strictEqual((nodes.adviserMatrixChoices.innerHTML.match(/data-matrix-all=/g) || []).length, 2);
assert(!nodes.adviserMatrixChoices.innerHTML.includes('Uncheck all'));
vm.runInContext('setAdviserMatrixGroup("parts", true, records)', context);
assert(nodes.adviserMatrixStatus.textContent.includes(`${parts.length} part(s)`));
assert(masters.parts.checked && !masters.parts.indeterminate);
vm.runInContext('setAdviserMatrixGroup("proposals", true, records)', context);
assert(nodes.adviserMatrixStatus.textContent.startsWith('2 proposal(s)'));
vm.runInContext('setAdviserMatrixGroup("parts", false, records)', context);
assert(nodes.adviserMatrixStatus.textContent === '2 proposal(s) · 0 part(s)');
assert(!masters.parts.checked && !masters.parts.indeterminate);
vm.runInContext('setAdviserMatrixGroup("proposals", false, records)', context);
assert(nodes.adviserMatrixStatus.textContent === '0 proposal(s) · 0 part(s)');
assert(!masters.proposals.checked && !masters.proposals.indeterminate);
vm.runInContext('renderAdviserMatrix([])', context);
assert(masters.proposals.disabled);
assert.strictEqual(JSON.stringify(source), before);
const css = fs.readFileSync(path.join(root, 'styles-upload.css'), 'utf8');
const page = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
assert(page.includes('class="adviser-comparison-layout"'));
assert(css.includes('grid-template-columns: 250px minmax(0, 1fr)'));
assert(css.includes('max-height: var(--matrix-panel-height); overflow: auto'));
assert(css.includes('.adviser-matrix-single { min-width: 100%; }'));
assert(css.includes('var(--proposal-count) * var(--matrix-column-min)'));
assert(css.includes('.adviser-comparison-layout { grid-template-columns: 1fr; }'));
console.log('Passed: full entries, numbered questions, composite fields, escaping, source links, selection/empty states, and immutable review data.');
